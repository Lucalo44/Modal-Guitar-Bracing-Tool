import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from helpers import ROOT, GOLD, OUT  # noqa: E402

DOCS = os.path.join(ROOT, 'docs'); FIG = os.path.join(DOCS, 'validation')
STAGE_NAMES = {1: 'Closed-form plate checks', 2: 'Exact solutions for the edge fixes', 3: 'Convergence on real designs',
               4: 'Invariance and smoothness', 5: 'Limits and consistency', 6: 'Independent 3D solid model (rectangle ladder)',
               7: 'Existing ANSYS guitar runs', 8: 'Optimizer behaviour', 9: 'Performance, parity, compatibility, robustness'}


def svg_convergence(name, v1, v2, path):
    """f vs 1/GN for modes 1-3, v1 dashed, v2 solid."""
    W, H, L, R, T, B = 420, 260, 50, 12, 14, 34
    pts = []
    for d in (v1, v2):
        if d:
            for g, fs in d.items():
                pts += [f for f in fs[:3]]
    if not pts:
        return
    lo, hi = min(pts)*0.97, max(pts)*1.03
    xs = lambda g: L + (1/g - 1/200)/(1/34 - 1/200)*(W - L - R)
    ys = lambda f: T + (hi - f)/(hi - lo)*(H - T - B)
    cols = ['#2f9fd6', '#de6a54', '#4e9e46']
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="Segoe UI, sans-serif" font-size="10">',
           f'<rect width="{W}" height="{H}" fill="#f6fcfb"/>']
    for g in (34, 50, 80, 120, 200):
        out.append(f'<line x1="{xs(g):.1f}" x2="{xs(g):.1f}" y1="{T}" y2="{H-B}" stroke="#dcebe8"/>'
                   f'<text x="{xs(g):.1f}" y="{H-B+13}" text-anchor="middle" fill="#4d6b64">{g}</text>')
    for k in range(5):
        f = lo + (hi - lo)*k/4
        out.append(f'<text x="{L-6}" y="{ys(f)+3:.1f}" text-anchor="end" fill="#4d6b64">{f:.0f}</text>')
    out.append(f'<text x="{(L+W-R)/2}" y="{H-6}" text-anchor="middle" fill="#4d6b64">GN (axis linear in 1/GN)</text>')
    for d, dash in ((v1, '4 3'), (v2, '')):
        if not d:
            continue
        gs = sorted(int(g) for g in d)
        for m in range(3):
            line = ' '.join(f'{xs(g):.1f},{ys(d[str(g)][m]):.1f}' for g in gs if len(d[str(g)]) > m)
            out.append(f'<polyline points="{line}" fill="none" stroke="{cols[m]}" stroke-width="2" stroke-dasharray="{dash}"/>')
    out.append(f'<text x="{L+4}" y="{T+10}" fill="#1f3b3a" font-weight="700">{name}: modes 1-3, v2 solid, v1 dashed</text>')
    out.append('</svg>')
    open(path, 'w').write('\n'.join(out))


def main():
    res = json.load(open(os.path.join(OUT, 'results.json')))
    checks, extra = res['checks'], res.get('extra', {})
    os.makedirs(FIG, exist_ok=True)
    gv1 = json.load(open(os.path.join(GOLD, 'baseline.json')))['fixtures']
    gv2p = os.path.join(GOLD, 'v2.json')
    gv2 = json.load(open(gv2p))['fixtures'] if os.path.exists(gv2p) else {}
    L = ['# Solver validation', '',
         f'Commit validated: `{res.get("commit")}` (branch `experimental`). Generated by `tests/make_report.py` from',
         '`tests/out/results.json`; rerun `python tests/validation.py --stages 1,2,3,4,5,6,7,8,9` then this script.', '']
    n_pass = sum(c['pass'] for c in checks)
    L += [f'**{n_pass} of {len(checks)} checks pass.**', '']
    for st in sorted({c['stage'] for c in checks}):
        L += [f'## Stage {st}: {STAGE_NAMES.get(st, "")}', '', '| Check | Measured | Limit | Result |', '|---|---|---|---|']
        for c in [c for c in checks if c['stage'] == st]:
            L.append(f"| {c['check']} | {c['measured']} | {c['limit']} | {'pass' if c['pass'] else '**fail**'} |")
        L.append('')
        if st == 3 and gv2:
            for name in gv2:
                p = os.path.join(FIG, f'convergence_{name}.svg')
                svg_convergence(name, {g: v['freqs'] for g, v in gv1.get(name, {}).items()},
                                {g: v['freqs'] for g, v in gv2[name].items()}, p)
                L.append(f'![{name}](validation/convergence_{name}.svg)')
            L.append('')
        if st == 6 and 'rect3d_v2' in extra:
            L += ['Per-mode error against the 3D solid (tool vs solid, %), v2 then v1:', '', '| Case | v2 modes 1-6 | v1 modes 1-6 |', '|---|---|---|']
            for k, r in extra['rect3d_v2'].items():
                r1 = extra.get('rect3d_v1', {}).get(k, {'err': []})
                L.append(f"| {k} | {' '.join(f'{e:+.1f}' for e in r['err'])} | {' '.join(f'{e:+.1f}' for e in r1['err'])} |")
            L.append('')
        if st == 7 and 'ansys' in extra:
            L += ['| Design | ANSYS (Hz) | v2 GN 120 (Hz) | v1 GN 120 (Hz) |', '|---|---|---|---|']
            for k, r in extra['ansys'].items():
                if isinstance(r, dict):
                    L.append(f"| {k} | {', '.join(f'{x:.0f}' for x in r['ansys'][:5])} | {', '.join(f'{x:.0f}' for x in r['v2'][:5])} | {', '.join(f'{x:.0f}' for x in r['v1'][:5])} |")
            for bc in ('bare_clamped', 'bare_ss'):
                if bc in extra['ansys']:
                    L.append(f"\nPredicted bare dreadnought top ({bc.split('_')[1]}, no bridge, plate shear 0.6/0.04 GPa, GN 160): "
                             + ', '.join(f'{x:.1f}' for x in extra['ansys'][bc][:6]) + ' Hz.')
            L.append('')
    L += ['## Known remaining error', '',
          '- **Brace-to-grid coupling.** A brace is a line beam reading a bilinear plate field, so the frequency ripples by about 1% per 0.1-cell move on the GN 34 search grid (0.4% at GN 80), and a braced top moves up to 1.9% when the grid is shifted under it. Bare tops move under 0.5%. This is handoff diagnosis item 3; the conforming finite element solve (P3) is what removes it.',
          '- **Brace fundamental.** Against the 3D solid, single and crossing braces still read 2-4% low on mode 1 with the 40-thickness flange; modes 2-6 are within about 3%.',
          '- **Existing ANSYS runs.** v2 reads well above the existing guitar ANSYS runs, by more than the 3D solid says it should. Stage 7 explains what to check in ANSYS (bare-plate run, fixed-support scope, contact formulation).', '']
    os.makedirs(DOCS, exist_ok=True)
    open(os.path.join(DOCS, 'validation.md'), 'w').write('\n'.join(L))
    print('wrote docs/validation.md')


if __name__ == '__main__':
    main()
