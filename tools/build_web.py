"""Builds the browser version (index.html at the repo root) from the one
UI source, desktop/ui/index.html, and the one engine, desktop/engine.py.

    python tools/build_web.py           # write index.html
    python tools/build_web.py --check   # exit 1 if index.html is out of date

The browser page loads PyScript and, at start-up, fetches desktop/engine.py
and runs it in Pyodide -- the same file the desktop app imports -- so the
two builds can't drift. It needs to be served over http(s) (GitHub Pages,
or `python -m http.server`), since a file:// page can't fetch the engine."""
import os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'desktop', 'ui', 'index.html')
DST = os.path.join(ROOT, 'index.html')

HEAD = '''<link rel="stylesheet" href="https://pyscript.net/releases/2026.3.1/core.css">
<script type="module" src="https://pyscript.net/releases/2026.3.1/core.js"></script>
'''

LOADER = '''<!-- ═══════════════════════════════════════════════════════════════════
     PYTHON ENGINE (numpy + scipy via PyScript/Pyodide). Generated by
     tools/build_web.py: the engine is NOT copied here; it's fetched from
     desktop/engine.py at start-up, the same file the desktop app runs.
     ═══════════════════════════════════════════════════════════════════ -->
<script type="py" config='{"packages": ["numpy", "scipy"]}' async>
import sys, types, js
from pyodide.http import pyfetch
from pyscript.ffi import create_proxy
_src = await (await pyfetch('desktop/engine.py')).string()
engine = types.ModuleType('engine')
sys.modules['engine'] = engine
exec(compile(_src, 'desktop/engine.py', 'exec'), engine.__dict__)
def _js(name):
    return lambda *a: getattr(js.window, name)(*a)
engine.set_bridge(**{n: _js(n) for n in engine.BRIDGE})
js.window.pyComputeBareModes = create_proxy(engine.compute_bare_modes)
js.window.pyRunAllPatterns = create_proxy(engine.run_all_patterns)
js.window.pyEvaluateManualDesign = create_proxy(engine.evaluate_manual_design)
js.window.pyCancelOptimizer = create_proxy(engine.request_cancel_optimizer)
js.window.onPyEngineReady()
</script>
'''


def build():
    s = open(SRC, encoding='utf-8').read()
    anchor = '<link rel="icon" type="image/png" href="logofinal.png">\n'
    assert anchor in s, 'icon link not found in desktop/ui/index.html'
    s = s.replace(anchor, anchor + HEAD, 1)
    # The desktop UI ends with a comment describing the native engine; swap it for the loader.
    start = s.rfind('<!-- ', 0, s.rfind('PYTHON OPTIMIZATION ENGINE'))
    end = s.find('-->', start) + 3
    assert start > 0 and end > start, 'engine comment block not found'
    s = s[:start] + LOADER + s[end:]
    return s


if __name__ == '__main__':
    out = build()
    if '--check' in sys.argv:
        cur = open(DST, encoding='utf-8').read() if os.path.exists(DST) else ''
        if cur != out:
            print('index.html is out of date: run python tools/build_web.py'); sys.exit(1)
        print('index.html is up to date'); sys.exit(0)
    open(DST, 'w', encoding='utf-8').write(out)
    print(f'wrote {DST} ({len(out)//1024} KB)')
